// Record shared/golden/reducer.json from a real scripted match.
//
// The events are exactly what player 1's socket received; each checkpoint holds
// the server's own state after a command (HP, status, hand, charges). Vitest
// feeds the events to the client reducer and checks it reaches the same state,
// so the vectors compare the client against the server, not against itself.
//
//   node scripts/gen-reducer-golden.js           # rewrite the file
//   node scripts/gen-reducer-golden.js --check   # record again and compare (ignoring times and ids)

import fs from 'node:fs';
import path from 'node:path';
import { SHARED_DIR } from '../src/config.js';
import { FakeClock } from '../src/clock.js';
import { Connection } from '../src/realtime/hub.js';
import { closeAll, FakeWS, makePlayer, seededDb, testContext } from '../test/helpers.js';

const OUT = path.join(SHARED_DIR, 'golden', 'reducer.json');

export async function record() {
  const db = await seededDb();
  const clock = new FakeClock(1_000_000, 1_790_000_000_000);
  const ctx = testContext(db, clock);
  await ctx.problems.reload(db);
  const p1 = await makePlayer(db, 1250, 'golden_one');
  const p2 = await makePlayer(db, 1250, 'golden_two');
  const actor = await ctx.matches.createMatch('ranked', 'bit', p1, p2, { seed: 2024 });
  const ws = { 1: new FakeWS(), 2: new FakeWS() };
  const checkpoints = [];
  const checkpoint = (label) => {
    const { m } = actor;
    checkpoints.push({
      label,
      after: ws[1].sent.length,
      expect: {
        status: m.status, hp: { 1: m.player1_hp, 2: m.player2_hp }, hand: [...actor.hands[1].slots],
        charges: { blocks: m.player1_blocks_left, hints: m.player1_hints_left, rerolls: m.player1_rerolls_left },
        inflight: actor.rt[1].inflight !== null, you: 1,
      },
    });
  };
  const settle = () => actor.settle();
  const advance = async (s) => {
    for (let i = 0; i < Math.trunc(s * 2); i++) {
      clock.advance(0.5);
      await settle();
    }
  };
  const tier = (n, t) => actor.hands[n].tiers.indexOf(t);
  const submit = (side, slot, verdict, id) => actor.send('submit', side, { slot, code: `# VERDICT: ${verdict}\n# DELAY_MS: 0\n`, language: 'python' }, id);

  for (const side of [1, 2]) await actor.send('join', side, { conn: new Connection(ws[side], 0), last_seq: 0 });
  checkpoint('joined');
  await advance(3.1);
  checkpoint('live');
  await submit(1, tier(1, 2), 'AC', 'g1');
  await settle();
  checkpoint('p1 hits with a tier-2 card');
  await advance(2);
  checkpoint('card re-dealt');
  await actor.send('hint', 1, { slot: tier(1, 1) }, 'g2');
  checkpoint('hint');
  await actor.send('block', 1, {}, 'g3');
  checkpoint('block');
  await submit(2, tier(2, 3), 'AC', 'g4');
  await settle();
  checkpoint('p2 hit is blocked');
  await advance(2);
  await submit(1, tier(1, 3), 'WA 2', 'g5');
  await settle();
  checkpoint('p1 backfires');
  await advance(20);
  checkpoint('shield expired and timers');
  await submit(2, tier(2, 1), 'AC', 'g6');
  await settle();
  checkpoint('p2 hits');
  await advance(4);
  await submit(1, tier(1, 4), 'AC', 'g7');
  await settle();
  checkpoint('p1 KO');
  await closeAll();
  return {
    _comment: 'generated by server/scripts/gen-reducer-golden.js from a real scripted match; checkpoints are the server\'s state',
    events: ws[1].sent, checkpoints,
  };
}

/**
 * Times, generated ids and the comment differ run to run, and the daily quests
 * differ by day. The weapon skin and the cards' animation level were added after
 * the committed recording; the client ignores fields it does not know. Everything
 * else must match.
 */
function stable(golden) {
  const strip = (v, key = '') => {
    if (Array.isArray(v)) return v.map((x) => strip(x));
    if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).filter(([k]) => !['t', 'id', '_comment', 'profile_id', 'weapon', 'level', 'quests'].includes(k)).map(([k, x]) => [k, strip(x, k)]));
    return key === 'submission_id' && v !== null ? 'id' : v;
  };
  return strip(golden);
}

if (process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname) {
  const out = await record();
  if (process.argv.includes('--check')) {
    const old = JSON.parse(fs.readFileSync(OUT, 'utf8'));
    const a = JSON.stringify(stable(old));
    const b = JSON.stringify(stable(out));
    console.log(a === b ? 'reducer.json: same events and checkpoints' : 'reducer.json DIFFERS');
    if (a !== b) {
      fs.writeFileSync('/tmp/reducer-new.json', JSON.stringify(out, null, 1));
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUT, `${JSON.stringify(out, null, 1)}\n`);
    console.log(`wrote ${out.events.length} events and ${out.checkpoints.length} checkpoints`);
  }
}
