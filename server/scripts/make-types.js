// Generate frontend/src/net/protocol.generated.ts from src/realtime/protocol.js.
//
//   node scripts/make-types.js          # write the file
//   node scripts/make-types.js --check  # fail if the committed file is stale

import fs from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from '../src/config.js';
import { EVENT_MODELS } from '../src/realtime/protocol.js';

const OUT = path.join(REPO_ROOT, 'frontend', 'src', 'net', 'protocol.generated.ts');

function tsType(t) {
  switch (t.kind) {
    case 'int': case 'num': return 'number';
    case 'str': return 'string';
    case 'bool': return 'boolean';
    case 'null': return 'null';
    case 'lit': return t.values.map((v) => (typeof v === 'string' ? `"${v}"` : String(v))).join(' | ');
    case 'list': return `Array<${tsType(t.item)}>`;
    case 'dict': return `Record<string, ${tsType(t.value)}>`;
    case 'union': return [...new Set(t.types.map(tsType))].join(' | ');
    case 'model': return t.name;
    default: return 'unknown';
  }
}

function collect(t, defs) {
  if (t.kind === 'model') {
    if (defs.has(t.name)) return;
    defs.set(t.name, t);
    for (const f of Object.values(t.fields)) collect(f.type, defs);
  } else if (t.kind === 'list') collect(t.item, defs);
  else if (t.kind === 'dict') collect(t.value, defs);
  else if (t.kind === 'union') t.types.forEach((x) => collect(x, defs));
}

function iface(m) {
  const lines = [`export interface ${m.name} {`];
  for (const [k, f] of Object.entries(m.fields)) lines.push(`  ${k}${f.optional ? '?' : ''}: ${tsType(f.type)};`);
  if (m.extra === 'allow') lines.push('  [key: string]: unknown;');
  lines.push('}\n');
  return lines.join('\n');
}

export function render() {
  const defs = new Map();
  for (const m of Object.values(EVENT_MODELS)) collect(m, defs);
  const out = ['// AUTO-GENERATED by server/scripts/make-types.js from server/src/realtime/protocol.js. Do not edit.\n'];
  for (const name of [...defs.keys()].sort()) out.push(iface(defs.get(name)));
  out.push('export interface EventDataMap {');
  for (const [t, m] of Object.entries(EVENT_MODELS)) out.push(`  "${t}": ${m.name};`);
  out.push('}\n');
  out.push('export type EventType = keyof EventDataMap;\n');
  out.push('export interface ServerMessage<T extends EventType = EventType> {\n  v: 1;\n  type: T;\n  seq?: number;\n  t: number;\n  data: EventDataMap[T];\n}\n');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname) {
  const text = render();
  const rel = path.relative(REPO_ROOT, OUT);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) {
      console.log(`${rel} is stale: run \`npm run types\``);
      process.exit(1);
    }
    console.log('protocol types are up to date');
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${rel} (${text.split('\n').length - 1} lines)`);
  }
}
